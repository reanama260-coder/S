// Build: gabungkan src/lib.js + src/providers/*.js -> providers/*.js (tanpa dependency, cukup `node build.js`)
// Hasil build WAJIB di-commit, karena Nuvio mengunduh providers/*.js langsung dari GitHub raw.
const fs = require('fs');
const path = require('path');

const lib = fs.readFileSync(path.join(__dirname, 'src/lib.js'), 'utf8');
const dir = path.join(__dirname, 'src/providers');
const out = path.join(__dirname, 'providers');
fs.mkdirSync(out, { recursive: true });

const files = fs.readdirSync(dir).filter((f) => f.endsWith('.js')).sort();
const mods = files.map((f) => {
  const code = fs.readFileSync(path.join(dir, f), 'utf8');
  const v = /@var\s+(\w+)/.exec(code);
  if (!v) throw new Error(f + ': baris "// @var NamaVariabel" tidak ada');
  return { file: f, id: f.replace(/\.js$/, ''), v: v[1], code };
});

const footer = (list) => `\nvar getStreams = makeGetStreams([${list.join(', ')}]);\nif (typeof module !== 'undefined' && module.exports) { module.exports = { getStreams: getStreams, onSettings: onSettings }; }\nif (typeof global !== 'undefined') { global.getStreams = getStreams; global.onSettings = onSettings; }\n`;
const banner = (name) => `/* Hentai Hub for Nuvio - ${name} (generated by build.js, edit src/ instead) */\n`;

mods.forEach((m) => {
  fs.writeFileSync(path.join(out, m.id + '.js'), banner(m.id) + lib + '\n' + m.code + footer([m.v]));
  console.log('built providers/' + m.id + '.js');
});
fs.writeFileSync(
  path.join(out, 'hentai-all.js'),
  banner('all') + lib + '\n' + mods.map((m) => m.code).join('\n') + footer(mods.map((m) => m.v))
);
console.log('built providers/hentai-all.js');
